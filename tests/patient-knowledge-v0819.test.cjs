'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),cp=require('node:child_process');
const root=path.resolve(__dirname,'..');
const profile=require('../data/patient-knowledge/00568.json');
const registry=require('../js/patient-asset-registry-v0810.js');
const protocol=require('../protocols/lung/00568-pembrolizumab-pemetrexed-and-carboplatin-auc5-therapy.json');
assert.equal(profile.protocol_id,protocol.protocol_id);
assert.equal(registry.relativePath(protocol,'knowledge'),'patient/00568/knowledge.html');
assert.equal(registry.relativePath(protocol,'consent-draft'),'patient/00568/consent-form.html');
assert.equal(registry.relativePath('00382','consent-draft'),null,'unsupported consent forms must not silently resolve to patient portals');
assert.equal(registry.relativePath('00222','consent-draft'),'patient/00222/consent-form.html');
assert.deepEqual(profile.phases[0].agents,['pembrolizumab','pemetrexed','carboplatin']);
assert.deepEqual(profile.phases[1].agents,['pembrolizumab','pemetrexed']);
assert.equal(profile.cycle_days,21);
assert.equal(profile.timeline.find(r=>r.id==='immune').end,21);
cp.execFileSync(process.execPath,['tools/build-patient-knowledge.cjs','--check'],{cwd:root,stdio:'inherit'});
const code=fs.readFileSync(path.join(root,'assets/patient/patient-knowledge.js'),'utf8');
assert.doesNotMatch(code,/localStorage|sessionStorage|fetch\(|XMLHttpRequest|sendBeacon/,'patient knowledge must not persist or transmit patient-entered data');
const consent=fs.readFileSync(path.join(root,'patient/00568/consent-form.html'),'utf8');
assert.match(consent,/Treatment discussion/i);
assert.match(consent,/Regimen \/ agent-specific material risks/i);
for(const drug of ['Pembrolizumab','Pemetrexed','Carboplatin']) assert.match(consent,new RegExp(drug,'i'));
for(const risk of ['Immune inflammation','lungs','bowel','liver','kidneys','glands','Mouth soreness','Kidney toxicity','Allergic reactions']) assert.match(consent,new RegExp(risk,'i'));
assert.doesNotMatch(consent,/textarea|discussion-benefit|discussion-alternatives/,'clinician consent generator should be a concise one-page form, not the old discussion worksheet');
const consentPdf=path.join(root,'patient/00568/consent-form.pdf');assert.ok(fs.existsSync(consentPdf)&&fs.statSync(consentPdf).size>10000,'one-page consent PDF must be present');
let opened='';global.open=url=>{opened=url;return {};};
const workflow=require('../js/regimen-workflow-engine-v0750.js');
workflow.openConsentSupport(protocol);assert.match(opened,/patient\/00568\/consent-form\.html$/);
console.log('Patient knowledge contract, one-page consent routing and consent-form content passed.');

let checks = 0;
function evaluate(label, inputs, expected, hit, forbidden) {
  const result = engine.assess(protocol, inputs);
  assert.deepEqual(result.errors, [], label);
  assert.deepEqual(result.invalid, [], label);
  if (expected) assert.equal(result.actionType, expected, label);
  const found = new Set(result.findings.map(item => item.ruleId));
  if (hit) assert.ok(found.has(hit), label);
  if (forbidden) assert.ok(!found.has(forbidden), label);
  checks++;
}

'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '../..');
const codes = ['00261', '00483', '00484', '00455', '00558'];
const read = file => JSON.parse(fs.readFileSync(path.join(root, file)));
const sha = file => crypto.createHash('sha256').update(fs.readFileSync(path.join(root, file))).digest('hex');
function validate(protocol, {allowUnchanged = false} = {}) {
  const code = protocol.metadata?.nccp_regimen_code;
  if (!codes.includes(code) || (!allowUnchanged && protocol.metadata.clinical_audit_release !== '0.84.46')) return null;
  const file = 'validation/head-neck-v08446/clinical/clinical-migration.json';
  const record = read(file);
  assert.equal(record.schema_version, 1);
  assert.equal(record.release, '0.84.46');
  assert.equal(record.baseline_commit, '628100a672ec51ccf25c7d27933fa9b43ac8f935');
  const row = record.protocols.find(item => item.code === code);
  const source = record.sources.find(item => item.code === code);
  assert(row && source, code + ' complete current audit record');
  assert.equal(sha(row.path), row.after_sha256, code + ' exact audited protocol');
  assert.deepEqual(protocol, read(row.path), code + ' passed object is not the audited protocol');
  assert.equal(sha(source.path), source.sha256, code + ' retained official PDF');
  assert.equal(protocol.metadata.nccp_version, source.version);
  assert.equal(protocol.metadata.source_url, source.url);
  assert.equal(sha(source.text_path), source.text_sha256);
  assert.equal(sha(record.audit.path), record.audit.sha256);
  const frozen = require('./retrospective-v08446.cjs').readFrozen(row.path);
  assert.equal(crypto.createHash('sha256').update(frozen).digest('hex'), row.before_sha256, code + ' exact Git45 baseline');
  assert.equal(sha(row.baseline_path), row.before_sha256, code + ' retained baseline copy');
  const previous = JSON.parse(frozen);
  const oldIds = new Set(previous.rule_engine.rules.map(r => r.id || r.rule_id));
  const newIds = protocol.rule_engine.rules.map(r => r.id || r.rule_id);
  assert.deepEqual(newIds.filter(id => !oldIds.has(id)).sort(), [...row.added_rule_ids].sort());
  assert.deepEqual([...oldIds].filter(id => !newIds.includes(id)).sort(), [...row.removed_rule_ids].sort());
  for (const key of ['clinical_use_authorised', 'consultant_reviewed', 'oncology_pharmacy_reviewed']) assert.equal(protocol.metadata.validation[key], false);
  const cases = record.source_cases;
  assert.equal(sha(cases.script), cases.sha256, 'Independently authored source cases');
  assert.equal(sha(cases.results), cases.results_sha256, 'Exact executed source-case report');
  const results = read(cases.results);
  assert.equal(results.total, cases.total);
  assert.equal(results.passed, cases.passed);
  assert.equal(results.passed, results.total);
  assert(results.cases.length === results.total && results.cases.every(item => item.pass === true));
  assert(results.cases.some(item => item.code === code), code + ' executed evidence');
  for (const id of row.added_rule_ids) assert(results.cases.some(item => item.code === code && item.expected?.yes?.includes(id) && item.actual?.ids?.includes(id)), id + ' independent positive source case');
  return {...row, result_path: cases.results};
}
module.exports = {validate, codes};
